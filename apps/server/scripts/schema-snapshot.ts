// `pnpm schema:snapshot` (FR-A-062, PD-05, data-model 8.3): regenerates what is committed next to the
// migrations, and exports the pieces `schema:check` and the tests compare it with.
//
//   drizzle/                      the migrations and drizzle-kit's own journal and snapshots (input)
//   schema-snapshots/NNNN-slug.sql   the DDL of a database produced by applying migrations 0000 up to
//                                 that version to an empty database (output)
//   schema-snapshots/migrations.json   tag, SHA-256 and schema version of every migration (output)
//
// The snapshot is taken from the MIGRATED database, not from `drizzle-kit export`: the export renders
// the TypeScript schema and would leave out the hand-written audit triggers (PD-05). What is dumped
// is `sqlite_master`: tables, then indexes, then triggers, each sorted by name, without `sqlite_%`
// objects and without the Drizzle bookkeeping table. Every version that ships gets its file in the
// same commit as its migration, before anyone needs it (baseline section 2: the one item that cannot
// be done later).
//
// Nothing here is part of the server bundle: this is development and CI tooling.
import { createHash } from 'node:crypto';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Database from 'better-sqlite3';
import { z } from 'zod';
import { migrateEmptyDatabase } from '../src/db/migrate.js';
import type { SqliteConnection } from '../src/db/open.js';

/** `apps/server`. */
export const PACKAGE_DIR: string = resolve(fileURLToPath(new URL('..', import.meta.url)));

export const MANIFEST_FILE_NAME = 'migrations.json';
const BOOKKEEPING_TABLE = '__drizzle_migrations';
const SNAPSHOT_HEADER_GENERATED =
  '-- generated by apps/server/scripts/schema-snapshot.ts; do not edit';

export interface SchemaPaths {
  /** `apps/server/drizzle`: the SQL files and `meta/`. */
  readonly migrationsFolder: string;
  /** `apps/server/schema-snapshots`. */
  readonly snapshotsFolder: string;
}

export function defaultPaths(packageDir: string = PACKAGE_DIR): SchemaPaths {
  return {
    migrationsFolder: join(packageDir, 'drizzle'),
    snapshotsFolder: join(packageDir, 'schema-snapshots'),
  };
}

// ---------------------------------------------------------------------------------------------
// The journal
// ---------------------------------------------------------------------------------------------

const JournalSchema = z.object({
  version: z.string(),
  dialect: z.string(),
  entries: z.array(
    z.object({
      idx: z.number().int(),
      version: z.string(),
      when: z.number().int(),
      tag: z.string(),
      breakpoints: z.boolean(),
    }),
  ),
});

export type Journal = z.infer<typeof JournalSchema>;
export type JournalEntry = Journal['entries'][number];

/** `0003_add_roles` gives `{ number: '0003', slug: 'add_roles' }`; anything else gives `undefined`. */
function parseTag(tag: string): { number: string; slug: string } | undefined {
  const match = /^(\d{4})_([a-z0-9_]+)$/.exec(tag);
  return match === null ? undefined : { number: match[1] ?? '', slug: match[2] ?? '' };
}

export function journalFile(migrationsFolder: string): string {
  return join(migrationsFolder, 'meta', '_journal.json');
}

/** The journal drizzle-kit keeps in `meta/_journal.json`. Throws when it is missing or malformed. */
export function readJournal(migrationsFolder: string): Journal {
  return JournalSchema.parse(JSON.parse(readFileSync(journalFile(migrationsFolder), 'utf8')));
}

/**
 * What is wrong with the migrations folder as a whole, in words; empty when it is well formed.
 *
 * `when` must strictly increase because the stock migrator compares only the newest applied
 * `created_at` with each entry and silently skips an older one (probe P13); tags must be `NNNN_slug`
 * in sequence so that position and name agree; a SQL file the journal does not list would never run,
 * and a journal entry without its file cannot run at all.
 */
export function journalProblems(migrationsFolder: string): string[] {
  let journal: Journal;
  try {
    journal = readJournal(migrationsFolder);
  } catch {
    return [`${journalFile(migrationsFolder)} is missing or is not a drizzle-kit journal`];
  }

  const problems: string[] = [];
  journal.entries.forEach((entry, position) => {
    const expectedNumber = String(position).padStart(4, '0');
    if (entry.idx !== position) {
      problems.push(
        `entry ${String(position)}: idx is ${String(entry.idx)}, expected ${String(position)}`,
      );
    }
    if (parseTag(entry.tag)?.number !== expectedNumber) {
      problems.push(
        `entry ${String(position)}: tag "${entry.tag}" must be ${expectedNumber}_<slug> (NNNN_slug, in sequence)`,
      );
    }

    const previous = journal.entries[position - 1];
    if (entry.when <= 0 || (previous !== undefined && entry.when <= previous.when)) {
      problems.push(
        `entry ${entry.tag}: "when" (${String(entry.when)}) must be greater than the previous entry's: the migrator skips an older one silently`,
      );
    }

    if (!existsSync(join(migrationsFolder, `${entry.tag}.sql`))) {
      problems.push(
        `${entry.tag}.sql is missing from the migrations folder (it is in the journal)`,
      );
    }
    const snapshotName = `${entry.tag.slice(0, 4)}_snapshot.json`;
    if (!existsSync(join(migrationsFolder, 'meta', snapshotName))) {
      problems.push(
        `meta/${snapshotName} is missing (drizzle-kit needs it to generate the next migration)`,
      );
    }
  });

  const journaled = new Set(journal.entries.map((entry) => `${entry.tag}.sql`));
  for (const name of readdirSync(migrationsFolder)
    .filter((file) => file.endsWith('.sql'))
    .sort()) {
    if (!journaled.has(name)) {
      problems.push(
        `${name} is in the migrations folder but not in meta/_journal.json: it would never run`,
      );
    }
  }
  return problems;
}

// ---------------------------------------------------------------------------------------------
// The manifest
// ---------------------------------------------------------------------------------------------

export interface ManifestEntry {
  readonly tag: string;
  /** SHA-256 of the whole SQL file, hex: the value the migrator records in `__drizzle_migrations`. */
  readonly sha256: string;
  /** The index of the migration: the schema version a database is at once it is applied. */
  readonly schemaVersion: number;
}

export const ManifestSchema = z.object({
  migrations: z.array(
    z.object({ tag: z.string(), sha256: z.string(), schemaVersion: z.number().int() }),
  ),
});

/** The hash the Drizzle migrator stores for a file: SHA-256 of its text. */
export function migrationHash(migrationsFolder: string, tag: string): string {
  const text = readFileSync(join(migrationsFolder, `${tag}.sql`)).toString();
  return createHash('sha256').update(text).digest('hex');
}

export function buildManifest(migrationsFolder: string): ManifestEntry[] {
  return readJournal(migrationsFolder).entries.map((entry, position) => ({
    tag: entry.tag,
    sha256: migrationHash(migrationsFolder, entry.tag),
    schemaVersion: position,
  }));
}

export function renderManifest(entries: readonly ManifestEntry[]): string {
  return `${JSON.stringify({ migrations: entries }, null, 2)}\n`;
}

// ---------------------------------------------------------------------------------------------
// Applying migrations to a scratch database
// ---------------------------------------------------------------------------------------------

/**
 * Apply the migrations of `migrationsFolder` to an (empty) scratch database, through the same
 * wrapper the server uses (`src/db/migrate.ts`: the only code that calls the Drizzle migrator).
 */
export function migrateScratchDatabase(db: SqliteConnection, migrationsFolder: string): void {
  migrateEmptyDatabase(db, migrationsFolder);
}

// ---------------------------------------------------------------------------------------------
// Snapshots
// ---------------------------------------------------------------------------------------------

/** `0000_init` becomes `0000-init.sql`. */
export function snapshotFileName(entry: Pick<ManifestEntry, 'tag'>): string {
  const parts = parseTag(entry.tag);
  if (parts === undefined) throw new Error(`"${entry.tag}" is not an NNNN_slug migration tag`);
  return `${parts.number}-${parts.slug}.sql`;
}

const OBJECT_ORDER: Readonly<Record<string, number>> = { table: 0, index: 1, trigger: 2 };

interface SchemaObject {
  readonly type: string;
  readonly name: string;
  readonly sql: string;
}

/** The DDL of a database, as `sqlite_master` stores it, in the fixed order of the snapshot rule. */
export function renderSnapshot(db: SqliteConnection, entry: ManifestEntry): string {
  const objects = (
    db
      .prepare(
        `SELECT type, name, sql FROM sqlite_master
         WHERE sql IS NOT NULL
           AND type IN ('table', 'index', 'trigger')
           AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\'
           AND tbl_name <> '${BOOKKEEPING_TABLE}'`,
      )
      .all() as SchemaObject[]
  ).sort(
    (a, b) =>
      (OBJECT_ORDER[a.type] ?? 99) - (OBJECT_ORDER[b.type] ?? 99) ||
      (a.name < b.name ? -1 : a.name > b.name ? 1 : 0),
  );

  return [
    `-- schema-version: ${String(entry.schemaVersion)}`,
    `-- last-migration: ${entry.tag}`,
    SNAPSHOT_HEADER_GENERATED,
    '',
    objects.map((object) => `${object.sql};`).join('\n\n'),
    '',
  ].join('\n');
}

/**
 * A new temporary folder that holds only migrations 0000 up to `version` (their SQL files and a
 * journal that lists just those), so that a database migrated from it ends at that version. The
 * caller removes the folder. Used for the snapshot of every version and by the upgrade harness.
 */
export function copyMigrationsUpTo(migrationsFolder: string, version: number): string {
  const journal = readJournal(migrationsFolder);
  const entries = journal.entries.slice(0, version + 1);
  const scratch = mkdtempSync(join(tmpdir(), 'm365portal-migrations-upto-'));
  mkdirSync(join(scratch, 'meta'));
  for (const entry of entries) {
    cpSync(join(migrationsFolder, `${entry.tag}.sql`), join(scratch, `${entry.tag}.sql`));
  }
  writeFileSync(journalFile(scratch), JSON.stringify({ ...journal, entries }));
  return scratch;
}

/**
 * The snapshot of every schema version, regenerated from the migrations: file name to text. Each
 * version is built by applying migrations 0000 up to it to a new empty database.
 */
export function buildSnapshots(migrationsFolder: string): Map<string, string> {
  const snapshots = new Map<string, string>();

  buildManifest(migrationsFolder).forEach((entry, position) => {
    const scratch = copyMigrationsUpTo(migrationsFolder, position);
    const db = new Database(':memory:');
    try {
      migrateScratchDatabase(db, scratch);
      snapshots.set(snapshotFileName(entry), renderSnapshot(db, entry));
    } finally {
      db.close();
      rmSync(scratch, { recursive: true, force: true });
    }
  });
  return snapshots;
}

/** Write the manifest and the snapshot of every version. Returns the files written. */
export function writeSchemaArtifacts(paths: SchemaPaths): string[] {
  const problems = journalProblems(paths.migrationsFolder);
  if (problems.length > 0) {
    throw new Error(`the migrations folder is not well formed:\n  ${problems.join('\n  ')}`);
  }
  mkdirSync(paths.snapshotsFolder, { recursive: true });
  const written: string[] = [];
  const manifestPath = join(paths.snapshotsFolder, MANIFEST_FILE_NAME);
  writeFileSync(manifestPath, renderManifest(buildManifest(paths.migrationsFolder)));
  written.push(MANIFEST_FILE_NAME);
  for (const [name, text] of buildSnapshots(paths.migrationsFolder)) {
    writeFileSync(join(paths.snapshotsFolder, name), text);
    written.push(name);
  }
  return written;
}

// ---------------------------------------------------------------------------------------------
// Command line
// ---------------------------------------------------------------------------------------------

/** `--package-dir <dir>` (default: this package), for tests and for a clean copy in CI. */
export function packageDirFromArguments(argv: readonly string[]): string {
  const at = argv.indexOf('--package-dir');
  const value = at >= 0 ? argv[at + 1] : undefined;
  return at >= 0 && value !== undefined ? resolve(value) : PACKAGE_DIR;
}

function main(argv: readonly string[]): number {
  const paths = defaultPaths(packageDirFromArguments(argv));
  try {
    const written = writeSchemaArtifacts(paths);
    process.stdout.write(
      `schema:snapshot wrote ${String(written.length)} files to ${paths.snapshotsFolder}:\n  ${written.join('\n  ')}\n`,
    );
    return 0;
  } catch (error) {
    process.stderr.write(
      `schema:snapshot failed: ${error instanceof Error ? error.message : String(error)}\n`,
    );
    return 1;
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
