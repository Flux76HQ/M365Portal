// The generator behind `worker-script.ps1` (Phase D, T-D-112, FR-D-102, PD-02): it renders the block
// of the script that holds the allow-list and the projections, with a SHA-256 of each, and splices
// it between two markers. `apps/server/scripts/generate-exchange-worker.ts` writes the result to the
// script and writes the two hashes to `generated-allow-list.ts`; `test/exchange/allow-list.test.ts`
// fails when either file is not what this module renders now, so the script cannot drift from the
// table the server validates against. The build copies the script as it is; nothing is rendered at
// runtime.
import { createHash } from 'node:crypto';
import { allowListManifest } from '@m365portal/shared/exchange/allow-list';
import { PROJECTIONS, RESULT_PROJECTION } from './projections.js';

export const GENERATED_BEGIN =
  '# >>> GENERATED (allow-list and projections): apps/server/scripts/generate-exchange-worker.ts, do not edit by hand >>>';
export const GENERATED_END = '# <<< END GENERATED <<<';

export const sha256Hex = (text: string): string =>
  createHash('sha256').update(text, 'utf8').digest('hex');

/** The canonical text of the projections: one line of JSON, in the order of the table. */
export function projectionManifest(): string {
  return JSON.stringify({ projections: PROJECTIONS, result: RESULT_PROJECTION, version: 1 });
}

/** A PowerShell single-quoted string literal: only the quote needs doubling. */
function psString(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

/** The generated block, markers included, without a trailing newline. */
export function renderGeneratedBlock(): string {
  const allow = allowListManifest();
  const projection = projectionManifest();
  return [
    GENERATED_BEGIN,
    `$script:AllowListJson = ${psString(allow)}`,
    `$script:AllowListSha256 = ${psString(sha256Hex(allow))}`,
    `$script:ProjectionJson = ${psString(projection)}`,
    `$script:ProjectionSha256 = ${psString(sha256Hex(projection))}`,
    GENERATED_END,
  ].join('\n');
}

/** The script with its generated block replaced by the current one. Throws when a marker is missing. */
export function spliceGeneratedBlock(script: string): string {
  const start = script.indexOf(GENERATED_BEGIN);
  const end = script.indexOf(GENERATED_END);
  if (start < 0 || end < start) throw new Error('the script has no generated block');
  return script.slice(0, start) + renderGeneratedBlock() + script.slice(end + GENERATED_END.length);
}

/** The text of `generated-allow-list.ts`: the two hashes the server pins. */
export function renderGeneratedModule(): string {
  return `// GENERATED by apps/server/scripts/generate-exchange-worker.ts (pnpm --filter @m365portal/server exchange:generate).
// Do not edit by hand: test/exchange/allow-list.test.ts fails when this file or worker-script.ps1 is
// not what the generator renders from packages/shared/src/exchange/allow-list.ts and projections.ts.
//
// The SHA-256 of the two manifests the script embeds. The session compares them with what the worker
// reports when it connects, so a worker that runs a script made from another table is stopped (PD-02).

export const ALLOW_LIST_MANIFEST_SHA256 =
  '${sha256Hex(allowListManifest())}';

export const PROJECTION_MANIFEST_SHA256 =
  '${sha256Hex(projectionManifest())}';
`;
}

/**
 * The cmdlets and functions the script may name besides the ten of the allow-list: language
 * built-ins, and the three of the Exchange Online module it imports. The scan in
 * `allow-list.test.ts` fails on a name that is on neither list.
 */
export function allowedBuiltIns(): readonly string[] {
  return [
    'Set-StrictMode',
    'ConvertFrom-Json',
    'ConvertTo-Json',
    'ConvertTo-SecureString',
    'Join-Path',
    'Get-Command',
    'Get-Module',
    'Import-Module',
    'Sort-Object',
    'Select-Object',
    'Where-Object',
    'ForEach-Object',
    'Out-Null',
    'Remove-Item',
    'Test-Path',
    'Connect-ExchangeOnline',
    'Disconnect-ExchangeOnline',
  ];
}
