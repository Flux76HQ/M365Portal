// local/no-ambient-time-random (PB-20, SB-34): in the Phase B server code the clock, the random
// source and the timers are injected, so a test moves a fake clock instead of sleeping.
import type { RuleTester } from 'eslint';
import { describe, expect, it } from 'vitest';
import { createRuleTester, ruleOf, scopeOf, STRICT_ASSERTIONS } from './support.js';

const FILE = 'apps/server/src/setup/runner.ts';
const SECRETS_FILE = 'apps/server/src/secrets/sealed-box.ts';
const rule = ruleOf('no-ambient-time-random');
const GLOBALS = {
  setTimeout: 'readonly',
  setInterval: 'readonly',
  setImmediate: 'readonly',
  Date: 'readonly',
  Math: 'readonly',
  crypto: 'readonly',
  globalThis: 'readonly',
} as const;

function ok(code: string, name?: string, filename = FILE): RuleTester.ValidTestCase {
  return { name: name ?? code, code, filename };
}

function time(
  code: string,
  name: string,
  label?: string,
  filename = FILE,
): RuleTester.InvalidTestCase {
  return {
    name: label ?? code,
    code,
    filename,
    errors: [{ messageId: 'ambientTime', data: { name } }],
  };
}

function random(
  code: string,
  name: string,
  label?: string,
  filename = FILE,
): RuleTester.InvalidTestCase {
  return {
    name: label ?? code,
    code,
    filename,
    errors: [{ messageId: 'ambientRandom', data: { name } }],
  };
}

createRuleTester().run('local/no-ambient-time-random', rule, {
  assertionOptions: STRICT_ASSERTIONS,
  valid: [
    ok('const now = clock.now();', 'the injected clock'),
    ok('const bytes = random.bytes(32);', 'the injected source'),
    ok('const jitter = random.float();'),
    ok('const handle = scheduler.setTimeout(callback, 10); scheduler.clearTimeout(handle);'),
    ok('scheduler.setInterval(tick, 60000);'),
    ok('const d = new Date(clock.now());', 'new Date with an argument'),
    ok("const d = new Date('2026-10-11T12:00:00.000Z');"),
    ok("const t = Date.parse('2026-10-11T12:00:00.000Z');", 'Date.parse converts a given value'),
    ok('const t = Date.UTC(2026, 9, 11);'),
    ok('const iso = new Date(ms).toISOString();'),
    ok('const x = other.now(); const y = other.random();', 'now and random on other objects'),
    ok('const t = this.clock.now();'),
    ok('const Date = fake; Date.now();', 'a local named Date'),
    ok('function f(setTimeout) { setTimeout(1); }', 'a parameter named setTimeout'),
    ok('const o = { setTimeout: 1 }; o.setTimeout;', 'a property named setTimeout'),
    ok('type T = typeof setTimeout;', 'naming the type of a timer'),
    ok(
      "import { createHash, timingSafeEqual, scryptSync } from 'node:crypto';",
      'crypto that is not random',
    ),
    ok("import { setTimeout } from './local-timers.js';", 'a local module', FILE),
    ok('const Math = fake; Math.random();', 'a local named Math'),
    ok('const id = crypto.subtle.digest(a, b);', 'crypto that is not random'),
    ok('const r = cryptoLike.randomUUID();', 'another object'),
    ok('const text = String(new Date(ms));'),
    // Secrets: keys, nonces and salts are generated by that folder.
    ok(
      "import { randomBytes } from 'node:crypto'; randomBytes(24);",
      'randomBytes in secrets',
      SECRETS_FILE,
    ),
    ok(
      "import crypto from 'node:crypto'; crypto.randomUUID();",
      'randomUUID in secrets',
      SECRETS_FILE,
    ),
    ok(
      'const key = crypto.getRandomValues(new Uint8Array(32));',
      'getRandomValues in secrets',
      SECRETS_FILE,
    ),
  ],

  invalid: [
    time('const t = Date.now();', 'Date.now'),
    time('const clock = { now: Date.now };', 'Date.now', 'Date.now passed along'),
    time("const t = Date['now']();", 'Date.now', 'computed key'),
    time('const t = globalThis.Date.now();', 'Date.now', 'through globalThis'),
    time('const { now } = Date; now();', 'Date.now', 'destructured'),
    time('const d = new Date();', 'new Date()'),
    time('const d = new Date;', 'new Date()', 'without parentheses'),
    time('const s = Date();', 'Date()', 'Date() without new returns the current time'),
    time('setTimeout(callback, 10);', 'setTimeout'),
    time('const h = setInterval(tick, 1000);', 'setInterval'),
    time('setImmediate(callback);', 'setImmediate'),
    time('const wait = promisify(setTimeout);', 'setTimeout', 'passed along'),
    time('globalThis.setTimeout(callback, 1);', 'setTimeout', 'through globalThis'),
    time("globalThis['setInterval'](tick, 1);", 'setInterval', 'computed key'),
    time('const { setTimeout } = globalThis; setTimeout(f, 1);', 'setTimeout', 'destructured'),
    time("import { setTimeout } from 'node:timers';", 'import from node:timers'),
    time("import timers from 'timers';", 'import from timers', 'the unprefixed module'),
    time(
      "import { setTimeout as sleep } from 'node:timers/promises';",
      'import from node:timers/promises',
    ),
    random('const r = Math.random();', 'Math.random'),
    random('const jitter = Math.random() * 100;', 'Math.random', 'in an expression'),
    random("const r = Math['random']();", 'Math.random', 'computed key'),
    random('const { random } = Math; random();', 'Math.random', 'destructured'),
    random('const id = crypto.randomUUID();', 'randomUUID', 'the global crypto'),
    random('const id = globalThis.crypto.randomUUID();', 'randomUUID', 'globalThis.crypto'),
    random('const b = crypto.getRandomValues(new Uint8Array(16));', 'getRandomValues'),
    random("import { randomUUID } from 'node:crypto';", 'randomUUID', 'the named import'),
    random("import { randomBytes } from 'crypto';", 'randomBytes', 'the unprefixed module'),
    random("import { randomInt as pick } from 'node:crypto';", 'randomInt', 'under an alias'),
    random(
      "import crypto from 'node:crypto'; const b = crypto.randomBytes(32);",
      'randomBytes',
      'a default import',
    ),
    random(
      "import * as nodeCrypto from 'node:crypto'; nodeCrypto.randomFillSync(buf);",
      'randomFillSync',
      'a namespace import',
    ),
    random(
      "import { webcrypto } from 'node:crypto'; webcrypto.getRandomValues(buf);",
      'getRandomValues',
      'webcrypto',
    ),
    random('const { randomUUID } = crypto; randomUUID();', 'randomUUID', 'destructured'),
    // The wall clock and the timers stay refused in secrets.
    time('const t = Date.now();', 'Date.now', 'the wall clock in secrets', SECRETS_FILE),
    time('setTimeout(f, 1);', 'setTimeout', 'a timer in secrets', SECRETS_FILE),
    random('Math.random();', 'Math.random', 'Math.random in secrets', SECRETS_FILE),
    {
      name: 'a declared global is still the global',
      code: 'Date.now(); setTimeout(f, 1); Math.random();',
      filename: FILE,
      languageOptions: { globals: GLOBALS },
      errors: [
        { messageId: 'ambientTime', data: { name: 'Date.now' } },
        { messageId: 'ambientTime', data: { name: 'setTimeout' } },
        { messageId: 'ambientRandom', data: { name: 'Math.random' } },
      ],
    },
  ],
});

describe('local/no-ambient-time-random: scope', () => {
  it('runs on the seven Phase B server folders and nowhere else', () => {
    const scope = scopeOf('no-ambient-time-random');

    expect(scope.files).toEqual([
      'apps/server/src/{setup,connection,auth,rbac,policy,integrations,secrets}/**/*.{ts,tsx,mts,cts,js,jsx,mjs,cjs}',
    ]);
    expect(scope.ignores).toEqual([]);
  });
});
